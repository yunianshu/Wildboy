/* Isolated real API/Vite acceptance. No real customer data or payment. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.ADMIN_URL||'http://127.0.0.1:5173');
  await page.getByRole('button',{name:'开发环境 · 演示登录'}).click();
  await page.getByRole('link',{name:/会员管理/}).click();
  await page.getByRole('heading',{name:'会员管理',exact:true}).waitFor();
  await page.getByRole('button',{name:'新建等级'}).click();
  const title='浏览器会员 '+Date.now();
  await page.getByLabel('等级名称',{exact:true}).fill(title);
  await page.getByLabel('SHOP启用优惠',{exact:true}).check();
  await page.getByLabel('SHOP定价值',{exact:true}).fill('8.5');
  await page.getByLabel('ACTIVITY启用优惠',{exact:true}).check();
  assert.equal(await page.getByLabel('活动多人优惠范围',{exact:true}).inputValue(),'');
  await page.getByLabel('活动多人优惠范围',{exact:true}).selectOption('ONE_BENEFIT');
  await page.getByLabel('ACTIVITY定价方式',{exact:true}).selectOption('REDUCTION');
  await page.getByLabel('ACTIVITY定价值',{exact:true}).fill('20');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('dialog').getByText('已保存',{exact:true}).waitFor();
  await page.getByRole('button',{name:'关闭弹窗',exact:true}).click();
  await page.getByText(title,{exact:true}).waitFor();
  const row=page.getByRole('row').filter({hasText:title});
  await row.getByRole('button',{name:'编辑等级'}).click();
  assert.equal(await page.getByLabel('SHOP定价值',{exact:true}).inputValue(),'8.5');
  assert.equal(await page.getByLabel('ACTIVITY定价值',{exact:true}).inputValue(),'20');
  assert.equal(await page.getByLabel('活动多人优惠范围',{exact:true}).inputValue(),'ONE_BENEFIT');
  await page.getByRole('button',{name:'关闭弹窗',exact:true}).click();
  await page.getByLabel('搜索用户',{exact:true}).fill('演示用户');
  await page.getByRole('button',{name:'搜索',exact:true}).click();
  const userRow=page.getByRole('row').filter({hasText:'演示用户'});
  await userRow.getByRole('button',{name:'编辑身份'}).click();
  await page.getByLabel('用户身份',{exact:true}).selectOption('MEMBER');
  await page.getByLabel('会员等级',{exact:true}).selectOption({label:title});
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('dialog').getByText('已保存',{exact:true}).waitFor();
  await page.getByRole('button',{name:'关闭弹窗',exact:true}).click();
  await userRow.getByText(title,{exact:true}).waitFor();
  await page.screenshot({path:'/tmp/wildboy-membership-admin.png',fullPage:true});
  await page.getByRole('link',{name:/活动订单/}).click();
  await page.getByRole('heading',{name:'活动订单',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/wildboy-activity-orders-admin.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS real browser membership navigation/create/edit/party-policy/assign/order-entry; no page errors');
})().catch(e=>{console.error(e);process.exit(1)});
