import json
from pathlib import Path
from playwright.sync_api import sync_playwright

BASE=Path(__file__).resolve().parent
OUT=BASE/'design-demos'/'qa-A'
OUT.mkdir(exist_ok=True)
URL=(BASE/'design-demos'/'dir-1.html').as_uri()
checks=[]
def check(name,condition,details=None):
    checks.append({'name':name,'pass':bool(condition),'details':details})
    if not condition: raise AssertionError(name+': '+str(details))

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
    page.goto(URL,wait_until='networkidle')
    page.evaluate('document.fonts.ready')
    check('desktop 8 rows',page.locator('#activityRows tr').count()==8)
    check('15 actual navigation entries',page.locator('#navigation a').count()==15)
    check('2 paid pending labels only',page.locator('.pending').count()==2)
    check('no pending zero',page.get_by_text('待支付 0',exact=True).count()==0)
    check('6 paid orders and 2 free lists',page.locator('#activityRows button.order').all_text_contents().count('收费订单')==6 and page.locator('#activityRows button.order').all_text_contents().count('免费名单')==2)
    check('currency has cents',page.get_by_text('¥68.00',exact=True).count()==1)
    check('all visible images loaded',page.locator('main img').evaluate_all('(els)=>els.every(e=>e.complete&&e.naturalWidth>0)'))
    check('Noto Sans SC loaded',page.evaluate('document.fonts.check(\'14px "Noto Sans SC"\')'))
    check('desktop no horizontal overflow',page.evaluate('document.documentElement.scrollWidth===innerWidth'))
    check('desktop primary control height 44',page.locator('#newActivity').bounding_box()['height']==44)
    page.screenshot(path=str(OUT/'desktop-1440x900.png'))
    page.fill('#query','山脊步道')
    page.locator('.filter-submit').click()
    check('search is title-only',page.locator('#emptyState').is_visible())
    page.screenshot(path=str(OUT/'empty-desktop.png'))
    page.locator('#clearEmpty').click()
    check('empty reset restores 8 and focus',page.locator('#activityRows tr').count()==8 and page.evaluate('document.activeElement.id')=='query')
    page.fill('#query','山脊')
    page.locator('.filter-submit').click()
    check('title search returns expected row',page.locator('#activityRows tr').count()==1 and page.locator('.activity-title').inner_text()=='周末山脊徒步')
    page.locator('#reset').click()
    page.select_option('#category',label='国内游行')
    check('category filter 2 rows',page.locator('#activityRows tr').count()==2)
    page.select_option('#status','PUBLISHED')
    check('combined filters expected row',page.locator('#activityRows tr').count()==1 and page.locator('.activity-title').inner_text()=='高山杜鹃两日行')
    page.locator('#reset').click()
    page.select_option('#status','DRAFT')
    check('draft filter 2 rows',page.locator('#activityRows tr').count()==2)
    page.locator('#reset').click()
    page.locator('#activityRows button.order').first.click()
    check('paid action opens honest order preview',page.locator('#dialogTitle').inner_text()=='收费订单 · 设计预览' and '未连接订单服务' in page.locator('#dialogCopy').inner_text())
    page.keyboard.press('Escape')
    check('row dialog Escape restores focus',page.evaluate('document.activeElement.dataset.action')=='orders')
    page.locator('#activityRows button.order').nth(1).click()
    check('free action opens honest list preview',page.locator('#dialogTitle').inner_text()=='免费名单 · 设计预览' and '未读取用户资料' in page.locator('#dialogCopy').inner_text())
    page.locator('#dialogConfirm').click()
    for link in page.locator('#navigation a').all():
        route=link.get_attribute('data-route')
        link.click()
        check('navigation '+route,'设计预览' in page.locator('#toast').inner_text())
    page.locator('#newActivity').click()
    check('new activity no false creation','未创建任何活动' in page.locator('#dialogCopy').inner_text())
    page.keyboard.press('Escape')
    page.locator('#previewTools summary').click()
    page.locator('#previewPublish').click()
    check('publish dialog matches Pen',page.locator('#dialogTitle').inner_text()=='发布这场活动？' and page.locator('#feedbackDialog').bounding_box()['width']==520)
    check('publish initial focus cancel',page.evaluate('document.activeElement.id')=='dialogCancel')
    page.screenshot(path=str(OUT/'publish-desktop.png'))
    page.keyboard.press('Escape')
    check('publish Escape and focus restored',not page.locator('#feedbackDialog').is_visible() and page.evaluate('document.activeElement.id')=='previewPublish')
    page.locator('#previewPublish').click()
    page.locator('#dialogConfirm').click()
    check('publish confirmation is honest preview','未发布任何活动' in page.locator('#toast').inner_text())
    page.locator('#previewKit').click()
    page.screenshot(path=str(OUT/'components-desktop.png'))
    page.keyboard.press('Escape')
    check('component dialog Escape returns focus',page.evaluate('document.activeElement.id')=='previewKit')
    page.locator('#previewTools summary').click()
    page.locator('#logout').click()
    check('logout no actual session mutation','当前未执行退出' in page.locator('#toast').inner_text())
    page.set_viewport_size({'width':375,'height':812})
    page.reload(wait_until='networkidle')
    page.evaluate('document.fonts.ready')
    check('mobile no horizontal overflow',page.evaluate('document.documentElement.scrollWidth===innerWidth'))
    check('mobile all rows retained',page.locator('#activityRows tr').count()==8)
    page.screenshot(path=str(OUT/'mobile-375x812.png'))
    page.screenshot(path=str(OUT/'mobile-full.png'),full_page=True)
    page.locator('#menuToggle').click()
    check('mobile navigation opens',page.locator('#sidebar').is_visible())
    page.locator('#logout').focus()
    page.keyboard.press('Tab')
    check('mobile navigation focus wraps',page.evaluate('document.activeElement===document.querySelector("#navigation a")'))
    page.screenshot(path=str(OUT/'mobile-navigation.png'))
    page.keyboard.press('Escape')
    check('mobile navigation Escape returns focus',page.evaluate('document.activeElement.id')=='menuToggle')
    page.locator('#previewTools summary').click()
    page.locator('#previewPublish').click()
    check('mobile dialog fits',page.locator('#feedbackDialog').bounding_box()['width']<=343)
    page.screenshot(path=str(OUT/'publish-mobile.png'))
    page.keyboard.press('Escape')
    check('mobile publish Escape returns focus',page.evaluate('document.activeElement.id')=='previewPublish')
    check('no JS or console errors',not errors,errors)
    browser.close()

report={'url':URL,'checks':checks,'passed':sum(c['pass'] for c in checks),'failed':sum(not c['pass'] for c in checks),'errors':errors}
(OUT/'validation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'passed':report['passed'],'failed':report['failed'],'output':str(OUT)},ensure_ascii=False))
